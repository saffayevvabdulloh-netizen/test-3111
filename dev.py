#!/usr/bin/env python3
"""One-command local start (Windows / macOS / Linux):   python dev.py

  1. checks Python version, creates .venv and installs backend/requirements.txt
  2. creates backend/.env for local work if missing (or diagnoses the existing one)
  3. builds the frontend once (needs Node.js) if frontend/dist is missing
  4. applies migrations and runs the server on http://127.0.0.1:8000

Options:  --check   only create/diagnose .env, then exit
          --no-frontend   skip the npm build      --rebuild   force the npm build
          --bot   check the Telegram bot connection (token, internet, proxy) and say what to fix
          --lan   open the site to phones/tablets on the same Wi-Fi
          --port 8000
"""
import argparse
import os
import secrets
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BACKEND, FRONTEND = ROOT / "backend", ROOT / "frontend"
ENV = BACKEND / ".env"
IS_WIN = os.name == "nt"

ENV_TEMPLATE = """# Local development settings (generated by dev.py). Comments go on their own lines.
DEBUG=True
SECRET_KEY={secret}
ALLOWED_HOSTS=localhost,127.0.0.1
# Without a bot token Telegram verification is skipped automatically in DEBUG mode.
# To test the real flow: put the BotFather token here and set REQUIRE_TELEGRAM_VERIFICATION=True
TELEGRAM_BOT_TOKEN=
TELEGRAM_BOT_USERNAME=TG_CODE_Verification_bot
"""

for _s in (sys.stdout, sys.stderr):  # never crash on Windows code pages (cp1251/cp1252)
    try:
        _s.reconfigure(errors="replace")
    except Exception:
        pass


def say(msg, kind="*"):
    print(f"[{kind}] {msg}", flush=True)


def ensure_env():
    if not ENV.exists():
        ENV.write_text(ENV_TEMPLATE.format(secret=secrets.token_urlsafe(50)), encoding="utf-8")
        say(f"created {ENV.relative_to(ROOT)} for local development", "+")
        return
    sys.path.insert(0, str(BACKEND))
    from root.envfile import parse_env_text  # same parser the server uses

    v = parse_env_text(ENV.read_text(encoding="utf-8"))
    token = v.get("TELEGRAM_BOT_TOKEN") or v.get("BOT_TOKEN") or v.get("TELEGRAM_TOKEN")
    debug = v.get("DEBUG", "False").lower() in ("1", "true", "yes", "on")
    if "BOT_TOKEN" in v and "TELEGRAM_BOT_TOKEN" not in v:
        say("backend/.env uses BOT_TOKEN - accepted as an alias, but TELEGRAM_BOT_TOKEN is the proper name.", "!")
    if not debug:
        say("DEBUG is not True in backend/.env -> production mode (strict hosts, secure defaults). For local work add DEBUG=True.", "!")
    if v.get("REQUIRE_TELEGRAM_VERIFICATION", "True").lower() in ("1", "true", "yes", "on") and not token:
        say("REQUIRE_TELEGRAM_VERIFICATION is on but no bot token is set: accounts can never be activated. "
            "Set TELEGRAM_BOT_TOKEN or REQUIRE_TELEGRAM_VERIFICATION=False.", "!")
    if "POSTGRES_PASSWORD" in v and "DATABASE_URL" not in v:
        say("This .env looks like the docker one (root .env.example). For local runs use backend/.env.example as a base.", "!")
    say("existing backend/.env checked", "+")


def dist_is_stale():
    """True when any frontend source file is newer than the built site (so fixes are never 'missing')."""
    built = FRONTEND / "dist" / "index.html"
    if not built.exists():
        return True
    t = built.stat().st_mtime
    watch = [FRONTEND / "package.json", FRONTEND / "index.html", FRONTEND / "vite.config.js"]
    for folder in (FRONTEND / "src", FRONTEND / "public"):
        watch.extend(p for p in folder.rglob("*") if p.is_file())
    return any(p.exists() and p.stat().st_mtime > t for p in watch)


def lan_ip():
    """This computer's address on the local network (no traffic is sent)."""
    import socket
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        s.connect(("10.255.255.255", 1))
        return s.getsockname()[0]
    except OSError:
        return "127.0.0.1"
    finally:
        s.close()


def run(cmd, cwd=None, **kw):
    say(" ".join(map(str, cmd)), "$")
    use_shell = bool(kw.pop("shell", False)) and IS_WIN  # npm is npm.cmd on Windows
    return subprocess.run(cmd, cwd=cwd, check=True, shell=use_shell, **kw)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--no-frontend", action="store_true")
    ap.add_argument("--rebuild", action="store_true")
    ap.add_argument("--port", default="8000")
    ap.add_argument("--bot", action="store_true", help="check the Telegram bot connection and explain what to fix")
    ap.add_argument("--lan", action="store_true", help="also open the site to phones/tablets on the same Wi-Fi")
    a = ap.parse_args()

    if sys.version_info < (3, 12):
        sys.exit(f"Python 3.12+ is required (you have {sys.version.split()[0]}). Install it from python.org and re-run.")
    ensure_env()
    if a.check:
        return

    venv = ROOT / ".venv"
    py = venv / ("Scripts/python.exe" if IS_WIN else "bin/python")
    if not py.exists():
        run([sys.executable, "-m", "venv", str(venv)])
    marker = venv / ".deps-ok"
    req = BACKEND / "requirements.txt"
    if not marker.exists() or marker.stat().st_mtime < req.stat().st_mtime:
        run([str(py), "-m", "pip", "install", "-r", str(req)])
        marker.write_text("ok")

    if not a.no_frontend and (a.rebuild or dist_is_stale()):
        say("frontend changed (or not built yet): building the site...", "*")
        npm = shutil.which("npm")
        if not npm:
            say("Node.js/npm not found: the site UI is not built (the API still works). Install Node 20+ from nodejs.org.", "!")
        else:
            run([npm, "install"], cwd=FRONTEND, shell=True)
            run([npm, "run", "build"], cwd=FRONTEND, shell=True)

    run([str(py), "manage.py", "migrate"], cwd=BACKEND)
    run([str(py), "manage.py", "ensure_admin"], cwd=BACKEND)
    if a.bot:  # diagnosis only: token ok? Telegram reachable? bot process alive?
        sys.exit(subprocess.run([str(py), "manage.py", "telegram_check"], cwd=BACKEND).returncode)
    host, env = "127.0.0.1", None
    if a.lan:
        host, env = "0.0.0.0", {**os.environ, "ALLOWED_HOSTS": "*"}  # real environment beats backend/.env
        say(f"on your phone/tablet (same Wi-Fi) open http://{lan_ip()}:{a.port}", "+")
        say("local network only: do not use --lan on a public network.", "!")
    say(f"open http://127.0.0.1:{a.port}   (Ctrl+C to stop)", "+")
    run([str(py), "manage.py", "runserver", f"{host}:{a.port}"], cwd=BACKEND, **({"env": env} if env else {}))


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        pass
    except subprocess.CalledProcessError as exc:
        sys.exit(f"\nStep failed (exit {exc.returncode}): {' '.join(map(str, exc.cmd))}\nSend this message to the developer.")
