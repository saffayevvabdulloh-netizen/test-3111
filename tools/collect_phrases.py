#!/usr/bin/env python3
"""Collect every sentence the app can SPEAK into frontend/public/audio/phrases.txt.

Run it again after you add/change mini games:   python tools/collect_phrases.py
Then regenerate the recordings:                  python tools/make_audio.py
(Anything missing from the recordings still works: the browser's own voice reads it.)
"""
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "frontend" / "src"
OUT = Path(__file__).resolve().parent.parent / "frontend" / "public" / "audio" / "phrases.txt"
S = r'"((?:[^"\\]|\\.)*)"'

for _s in (sys.stdout, sys.stderr):  # never crash on Windows code pages (cp1251/cp1252)
    try:
        _s.reconfigure(errors="replace")
    except Exception:
        pass


def read(p):
    return (SRC / p).read_text(encoding="utf-8")


def unesc(s):
    return s.replace('\\"', '"').replace("\\'", "'")


def block(src, name):
    """text of `const NAME = [ ... ];` (first match)"""
    m = re.search(r"const %s\s*=\s*\[(.*?)\n\];" % name, src, re.S)
    return m.group(1) if m else ""


def main():
    ph = set()
    speech, social, emo, frame, mood, parts = (read(f) for f in (
        "activities/games/speech.jsx", "activities/games/social.jsx", "activities/games/emotions.jsx",
        "activities/frame.jsx", "ui/MoodCheckin.jsx", "layouts/Parts.jsx"))
    # letters / alphabet: "A. Arslon"
    for l, w in re.findall(r'\{ l: %s, word: %s' % (S, S), speech):
        ph.add(f"{unesc(l)}. {unesc(w)}")
    for l, w in re.findall(r'\[%s, %s, "[^"]*"\]' % (S, S), block(speech, "ALIFBO")):
        ph.add(f"{unesc(l)}. {unesc(w)}")
    # greetings
    for t in re.findall(r'\{ t: %s, e:' % S, block(speech, "PHRASES")):
        ph.add(unesc(t))
    # stories
    for name in ("SCHOOL", "QUEUE"):
        for t in re.findall(r'\{ e: "[^"]*", t: %s \}' % S, block(social, name)):
            ph.add(unesc(t))
    # situations: the question, and the explanation of the right answer
    for q in re.findall(r'\bq: %s' % S, social):
        ph.add(unesc(q))
    for w in re.findall(r'good: true, why: %s' % S, social):
        ph.add(unesc(w))
    # emotions
    for label in re.findall(r'label: %s' % S, block(emo, "EMO")):
        ph.add(f"{unesc(label)}. Qaysi yuz {unesc(label)}?")
    # praise + gentle lines, finish lines, counting, mood check-in, voice test
    for name in ("CHEER", "GENTLE"):
        m = re.search(r"const %s = \[(.*?)\];" % name, frame, re.S)
        ph.update(unesc(t) for t in re.findall(S, m.group(1))) if m else None
    ph.update(["Ajoyib! Hammasini xatosiz bajarding!", "Barakalla! Mashqni tugatding!"])
    ph.update(["bir", "ikki", "uch", "to'rt", "besh", "olti"])
    ph.update(unesc(t) for t in re.findall(r'say: %s' % S, mood))
    ph.update(unesc(t) for t in re.findall(r'say: %s' % S, read("activities/games/calm.jsx")))  # breathing cues
    ph.update(unesc(t) for t in re.findall(r'speak\(%s\)' % S, parts))
    # page explanations + bot states (utils/guide.js), what each mini game says about itself, spoken error messages
    ph.update(unesc(t) for t in re.findall(r'\b\w+:\s*%s' % S, read("utils/guide.js")))
    ph.update(unesc(t) for t in re.findall(r'\bhow: %s' % S, read("activities/registry.js")))
    errors = read("api/errors.js")
    ph.update(unesc(t) for t in re.findall(r'"\s*:\s*%s' % S, errors))     # "English/Russian message": "Uzbek message"
    ph.update(unesc(t) for t in re.findall(r'=>\s*%s' % S, errors))        # [/regex/, () => "Uzbek message"]
    ph = sorted(p.strip() for p in ph if p.strip())
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("# one sentence per line; generated by tools/collect_phrases.py\n" + "\n".join(ph) + "\n", encoding="utf-8")
    print(f"{len(ph)} phrases -> {OUT.relative_to(OUT.parents[3])}")


if __name__ == "__main__":
    main()
